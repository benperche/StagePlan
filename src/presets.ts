// ---------------------------------------------------------------------------
// Section → Row packing
// ---------------------------------------------------------------------------

/**
 * Convert a preset + optional count overrides into a ChartConfig-ready row array.
 * Sections are packed into rows of maxPerRow chairs, colored by section.
 * Stands are applied per-section based on standMode (default 'solo').
 */
export function buildRowsFromSections(
  sections: PresetSection[],
  maxPerRow = 12,
): Row[] {
  // Flatten all chairs with stands applied per section
  const allChairs: Chair[] = []
  for (const section of sections) {
    const standMode = section.standMode ?? 'solo'
    for (let i = 0; i < section.count; i++) {
      const chair: Chair = {
        id: crypto.randomUUID(),
        enabled: true,
        color: section.color,
        label: section.instrument,
        hasStand: standMode === 'solo',
        standAfter: standMode === 'shared' && (i % 2 === 0) && (i + 1 < section.count),
      }
      allChairs.push(chair)
    }
  }

  // Pack into rows
  const rows: Row[] = []
  let i = 0
  const rowLabels = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
  while (i < allChairs.length) {
    const rowChairs = allChairs.slice(i, i + maxPerRow)
    rows.push({
      id: crypto.randomUUID(),
      chairs: rowChairs,
      label: rowLabels[rows.length] ?? String(rows.length + 1),
      fontSize: 11,
    })
    i += maxPerRow
  }

  return rows
}

// ---------------------------------------------------------------------------
// Boosey & Hawkes orchestra notation
//
// Format: `Ww - Br [- Perc] - Str` — each block is a dot-separated list of
// player counts. A count may carry a parenthesised doubling list, e.g.
// `3(III=Bass Clarinet)` or `2(I=Picc, II=Alto Fl)`.
//
// Examples:
//   2.2.2.2 - 4.2.3.1 - 1.2 - 12.10.8.8.6   (Brahms-sized)
//   1.1.1.1 - 2.0.0.0 - 0 - 6.5.4.3.2       (Mozart-sized chamber)
//   3.3.3.3 - 4.3.3.1 - 1.2 - 14.12.10.8.6  (Tchaikovsky-sized)
// ---------------------------------------------------------------------------

const ROMAN_TO_INT: Record<string, number> = {
  I: 1, II: 2, III: 3, IV: 4, V: 5, VI: 6, VII: 7, VIII: 8, IX: 9, X: 10,
}

interface ParsedInstrument {
  count: number
  doublings: Map<number, string>   // 1-indexed position → doubling label
}

interface ParsedSlot {
  name: string                     // canonical short name (e.g. "Fl")
  parsed: ParsedInstrument
}

export interface OrchestraComposition {
  woodwinds: ParsedSlot[]
  brass: ParsedSlot[]
  percussion: ParsedSlot[]
  strings: ParsedSlot[]
}

const WW_NAMES   = ['Fl', 'Ob', 'Cl', 'Bn']
const BR_NAMES   = ['Hn', 'Tp', 'Tb', 'Tu']
const PERC_NAMES = ['Timp', 'Perc']
const STR_NAMES  = ['V1', 'V2', 'Va', 'Vc', 'Cb']

function parseEntry(entry: string): ParsedInstrument {
  const trimmed = entry.trim()
  if (!trimmed || trimmed === '0') return { count: 0, doublings: new Map() }
  const m = trimmed.match(/^(\d+)(?:\((.+)\))?$/)
  if (!m) return { count: 0, doublings: new Map() }
  const count = parseInt(m[1], 10)
  const doublings = new Map<number, string>()
  if (m[2]) {
    for (const part of m[2].split(',').map(s => s.trim())) {
      const eq = part.indexOf('=')
      if (eq < 0) continue
      const posRaw = part.slice(0, eq).trim().toUpperCase()
      const label = part.slice(eq + 1).trim()
      const idx = ROMAN_TO_INT[posRaw] ?? parseInt(posRaw, 10)
      if (idx && label) doublings.set(idx, label)
    }
  }
  return { count, doublings }
}

function parseBlock(block: string, names: string[]): ParsedSlot[] {
  return block.split('.').map((entry, i) => ({
    name: names[i] ?? `?${i + 1}`,
    parsed: parseEntry(entry),
  }))
}

export function parseOrchestraNotation(notation: string): OrchestraComposition | null {
  const blocks = notation.split(/\s*-\s*/).map(b => b.trim()).filter(b => b)
  if (blocks.length < 3 || blocks.length > 4) return null
  let wwBlock: string, brBlock: string, percBlock: string | null = null, strBlock: string
  if (blocks.length === 3) {
    [wwBlock, brBlock, strBlock] = blocks
  } else {
    [wwBlock, brBlock, percBlock, strBlock] = blocks
  }
  return {
    woodwinds:  parseBlock(wwBlock,  WW_NAMES),
    brass:      parseBlock(brBlock,  BR_NAMES),
    percussion: percBlock ? parseBlock(percBlock, PERC_NAMES) : [],
    strings:    parseBlock(strBlock, STR_NAMES),
  }
}

/** Human-readable summary of a parsed composition, used by the modal preview. */
export function describeComposition(comp: OrchestraComposition): string {
  const longNames: Record<string, string> = {
    Fl: 'Flute', Ob: 'Oboe', Cl: 'Clarinet', Bn: 'Bassoon',
    Hn: 'French Horn', Tp: 'Trumpet', Tb: 'Trombone', Tu: 'Tuba',
    Timp: 'Timpani', Perc: 'Percussion',
    V1: 'Violin I', V2: 'Violin II', Va: 'Viola', Vc: 'Cello', Cb: 'Double Bass',
  }
  const lines: string[] = []
  const fmtBlock = (label: string, slots: ParsedSlot[]) => {
    const parts = slots
      .filter(s => s.parsed.count > 0)
      .map(s => {
        const long = longNames[s.name] ?? s.name
        const dbl = [...s.parsed.doublings.entries()]
          .map(([pos, lab]) => `${pos === 1 ? 'I' : pos === 2 ? 'II' : pos === 3 ? 'III' : String(pos)}=${lab}`)
          .join(', ')
        const annot = dbl ? ` (${dbl})` : ''
        return `${s.parsed.count} ${long}${annot}`
      })
    if (parts.length) lines.push(`${label}: ${parts.join(', ')}`)
  }
  fmtBlock('Woodwinds',  comp.woodwinds)
  fmtBlock('Brass',      comp.brass)
  fmtBlock('Percussion', comp.percussion)
  fmtBlock('Strings',    comp.strings)
  const total = [...comp.woodwinds, ...comp.brass, ...comp.percussion, ...comp.strings]
    .reduce((s, slot) => s + slot.parsed.count, 0)
  lines.push(`Total: ${total} players`)
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Build rows from a parsed orchestra composition.
//
// Layout strategy (semicircle, conductor at front):
//  - Strings closest to the conductor (innermost arc), grouped together.
//    Larger orchestras split strings across multiple rows; smaller ones
//    pack all bowed strings into one front row with bass behind.
//  - Winds in 1–2 rows behind strings (Fl/Ob front, Cl/Bn back when wide).
//  - Brass behind winds.
//  - Percussion in the back row.
//
// Stand placement:
//  - Strings get shared stands (every two players share).
//  - Winds, brass, percussion get solo stands (one per player).
// ---------------------------------------------------------------------------

function makeChairFromSlot(slot: ParsedSlot, chairIndex: number, color: string, mode: 'solo' | 'shared'): Chair {
  const dbl = slot.parsed.doublings.get(chairIndex + 1)
  const label = dbl ? `${slot.name}/${dbl}` : slot.name
  return {
    id: crypto.randomUUID(),
    enabled: true,
    color,
    label,
    hasStand: mode === 'solo',
    standAfter: false,   // set later for shared mode at the row level
  }
}

// A disabled placeholder used to keep the semicircle row shape consistent
// when a string section runs out of players in the back rows.
function makePlaceholderChair(color: string): Chair {
  return {
    id: crypto.randomUUID(),
    enabled: false,
    color,
    label: '',
    hasStand: false,
    standAfter: false,
  }
}

function rowFromSlots(
  slots: ParsedSlot[],
  color: string,
  mode: 'solo' | 'shared',
  rowLabel: string,
): Row | null {
  const chairs: Chair[] = []
  for (const slot of slots) {
    if (!slot || slot.parsed.count === 0) continue
    const sectionStart = chairs.length
    for (let i = 0; i < slot.parsed.count; i++) {
      chairs.push(makeChairFromSlot(slot, i, color, mode))
    }
    // For shared mode, pair stands within this section only (so no shared
    // stand bridges across two different instrument groups in the same row).
    if (mode === 'shared') {
      for (let i = sectionStart; i + 1 < sectionStart + slot.parsed.count; i += 2) {
        chairs[i].standAfter = true
      }
    }
  }
  if (chairs.length === 0) return null
  return {
    id: crypto.randomUUID(),
    chairs,
    label: rowLabel,
    fontSize: 11,
  }
}

export interface OrchestraRowsResult {
  rows: Row[]
  /** Number of rows from the back to render as straight lines instead of arcs.
   *  Bowed string sections (V1/V2/Va/Vc) sit in the front arc; everything
   *  behind them (Cb, winds, brass, percussion) renders in straight rows so
   *  small sections like a pair of horns don't get stretched across the
   *  whole back of the stage. */
  straightRows: number
}

export function buildOrchestraRows(comp: OrchestraComposition): OrchestraRowsResult {
  const rows: Row[] = []
  const labels = 'ABCDEFGHIJKLMN'
  let arcRowCount = 0
  const pushRow = (chairs: Chair[], isArc: boolean) => {
    if (chairs.length === 0) return
    rows.push({
      id: crypto.randomUUID(),
      chairs,
      label: labels[rows.length] ?? String(rows.length + 1),
      fontSize: 11,
    })
    if (isArc) arcRowCount++
  }
  const pushSectionRow = (slots: ParsedSlot[], color: string, mode: 'solo' | 'shared') => {
    const r = rowFromSlots(slots, color, mode, '')
    if (r) pushRow(r.chairs, false)
  }

  // ---- Bowed strings (V1/V2/Va/Vc): one desk per part per row ----
  // Strings fan back in concentric arcs. Each row has one desk (pair) of
  // every bowed string section. When a section runs out (it's smaller than
  // the longest), the slot is filled with a disabled placeholder chair so
  // the semicircle row stays the same shape across the back. Odd-count
  // sections end with a single chair on its own stand.
  const v1 = comp.strings[0], v2 = comp.strings[1], va = comp.strings[2], vc = comp.strings[3], cb = comp.strings[4]
  const bowedSlots = [v1, v2, va, vc].filter((s): s is ParsedSlot => !!s && s.parsed.count > 0)

  if (bowedSlots.length > 0) {
    const numStringRows = Math.max(...bowedSlots.map(s => Math.ceil(s.parsed.count / 2)))
    for (let r = 0; r < numStringRows; r++) {
      const rowChairs: Chair[] = []
      for (const s of bowedSlots) {
        const startIdx = r * 2
        const remaining = s.parsed.count - startIdx
        if (remaining >= 2) {
          // Full desk
          const c1 = makeChairFromSlot(s, startIdx,     COLORS.strings, 'shared')
          const c2 = makeChairFromSlot(s, startIdx + 1, COLORS.strings, 'shared')
          c1.standAfter = true
          rowChairs.push(c1, c2)
        } else if (remaining === 1) {
          // Last lone chair: solo stand, plus a placeholder to keep the desk-pair shape
          rowChairs.push(makeChairFromSlot(s, startIdx, COLORS.strings, 'solo'))
          rowChairs.push(makePlaceholderChair(COLORS.strings))
        } else {
          // Section exhausted: two placeholders to preserve the row shape
          rowChairs.push(makePlaceholderChair(COLORS.strings))
          rowChairs.push(makePlaceholderChair(COLORS.strings))
        }
      }
      pushRow(rowChairs, true)
    }
  }

  // ---- Double basses: one or two straight rows behind the cellos ----
  // Up to 4 basses → one row. 5+ basses → two rows roughly evenly split,
  // with the front row carrying the larger half (and full desks).
  if (cb && cb.parsed.count > 0) {
    const cbCount = cb.parsed.count

    const pushCbRow = (startIdx: number, count: number) => {
      const chairs: Chair[] = []
      for (let i = 0; i < count; i++) {
        const c = makeChairFromSlot(cb, startIdx + i, COLORS.strings, 'shared')
        if (i % 2 === 0) {
          const paired = (i + 1 < count)
          c.standAfter = paired
          c.hasStand = !paired   // lone last chair gets a solo stand
        }
        chairs.push(c)
      }
      pushRow(chairs, false)
    }

    if (cbCount > 4) {
      // Round front row up to even so it holds full desks; any odd remainder
      // ends up alone in the back row.
      const half = Math.ceil(cbCount / 2)
      const firstRowCount = (half % 2 === 0) ? half : half + 1
      pushCbRow(0, firstRowCount)
      pushCbRow(firstRowCount, cbCount - firstRowCount)
    } else {
      pushCbRow(0, cbCount)
    }
  }

  // ---- Winds: solo stands, one or two straight rows ----
  const fl = comp.woodwinds[0], ob = comp.woodwinds[1], cl = comp.woodwinds[2], bn = comp.woodwinds[3]
  const totalWinds = comp.woodwinds.reduce((s, slot) => s + (slot?.parsed.count ?? 0), 0)
  const splitWinds = totalWinds > 6 &&
    ((fl?.parsed.count ?? 0) + (ob?.parsed.count ?? 0)) > 0 &&
    ((cl?.parsed.count ?? 0) + (bn?.parsed.count ?? 0)) > 0
  if (splitWinds) {
    pushSectionRow([fl, ob], COLORS.woodwind, 'solo')
    pushSectionRow([cl, bn], COLORS.woodwind, 'solo')
  } else if (totalWinds > 0) {
    pushSectionRow(comp.woodwinds, COLORS.woodwind, 'solo')
  }

  // ---- Brass: one straight row ----
  if (comp.brass.reduce((s, slot) => s + slot.parsed.count, 0) > 0) {
    pushSectionRow(comp.brass, COLORS.brass, 'solo')
  }

  // ---- Percussion: back straight row ----
  if (comp.percussion.reduce((s, slot) => s + slot.parsed.count, 0) > 0) {
    pushSectionRow(comp.percussion, COLORS.percussion, 'solo')
  }

  return { rows, straightRows: rows.length - arcRowCount }
}
